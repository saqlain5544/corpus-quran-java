/**
 * Quran metadata: page and juz boundaries (Madani Mushaf 15-line).
 *
 * These are static reference data — moving them out of utils keeps the
 * utils file lean and makes the metadata easily cacheable.
 */

/** Approximate Madani Mushaf page for a given surah:verse. */
export function getPageNumber(surah: number, verse: number): number {
  for (let i = PAGE_MAP.length - 1; i >= 0; i--) {
    const [ps, pv, page] = PAGE_MAP[i];
    if (surah > ps || (surah === ps && verse >= pv)) {
      return page;
    }
  }
  return 1;
}

/** Juz number (1-30) for a given surah:verse. */
export function getJuzNumber(surah: number, verse: number): number {
  for (let j = JUZ_STARTS.length - 1; j >= 0; j--) {
    const [js, jv] = JUZ_STARTS[j];
    if (surah > js || (surah === js && verse >= jv)) {
      return j + 1;
    }
  }
  return 1;
}

